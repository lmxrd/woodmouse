//! File storage behind a small trait, so the bytes can live somewhere other than the local disk
//! later (a Nextcloud/WebDAV share, S3, ...). Every stored file records which backend holds it
//! (`storage_backend`) and where (`storage_key`), so several backends can coexist: a file is always
//! read from the backend that wrote it, whichever one is the default for new uploads.
//!
//! Today there is one backend, `local`, and the registry holds exactly one entry. Configuration:
//!   STORAGE_BACKEND  which backend new uploads use (default `local`)
//!   DATA_DIR         root for the local backend; files live in `<DATA_DIR>/files` (default `./data`)
//!   MAX_UPLOAD_MB    largest accepted upload (default 25)

use std::collections::HashMap;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::Arc;

use async_trait::async_trait;
use sha2::{Digest, Sha256};

/// Lowercase hex SHA-256 of `bytes` — the digest recorded on file rows, used to
/// deduplicate uploads and to spot identical file versions. sha2 0.11's digest
/// output no longer formats as hex, so the encoding is done here.
pub fn sha256_hex(bytes: &[u8]) -> String {
    let digest = Sha256::digest(bytes);
    let mut hex = String::with_capacity(2 * digest.len());
    for byte in digest.iter() {
        use std::fmt::Write as _;
        let _ = write!(&mut hex, "{byte:02x}");
    }
    hex
}

#[async_trait]
pub trait FileStore: Send + Sync {
    /// The name recorded on file rows (`local`, ...).
    fn name(&self) -> &str;
    async fn put(&self, key: &str, data: Vec<u8>) -> io::Result<()>;
    async fn get(&self, key: &str) -> io::Result<Vec<u8>>;
    /// Delete the object; a missing object is not an error.
    async fn delete(&self, key: &str) -> io::Result<()>;
}

/// Stores files as plain files under a root directory.
pub struct LocalDisk {
    root: PathBuf,
}

impl LocalDisk {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    /// Keys are generated by the server (`<workspace>/<uuid>`), but never trust them to stay inside
    /// the root.
    fn path(&self, key: &str) -> io::Result<PathBuf> {
        let safe = Path::new(key)
            .components()
            .all(|c| matches!(c, std::path::Component::Normal(_)));
        if key.is_empty() || !safe {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "invalid storage key",
            ));
        }
        Ok(self.root.join(key))
    }
}

#[async_trait]
impl FileStore for LocalDisk {
    fn name(&self) -> &str {
        "local"
    }

    async fn put(&self, key: &str, data: Vec<u8>) -> io::Result<()> {
        let path = self.path(key)?;
        if let Some(parent) = path.parent() {
            tokio::fs::create_dir_all(parent).await?;
        }
        tokio::fs::write(path, data).await
    }

    async fn get(&self, key: &str) -> io::Result<Vec<u8>> {
        tokio::fs::read(self.path(key)?).await
    }

    async fn delete(&self, key: &str) -> io::Result<()> {
        match tokio::fs::remove_file(self.path(key)?).await {
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
            other => other,
        }
    }
}

/// The registered backends and which one new uploads go to.
#[derive(Clone)]
pub struct FileStores {
    default: String,
    stores: HashMap<String, Arc<dyn FileStore>>,
    pub max_upload_bytes: u64,
}

impl FileStores {
    pub fn new(default: Arc<dyn FileStore>, max_upload_bytes: u64) -> Self {
        let name = default.name().to_string();
        Self {
            default: name.clone(),
            stores: HashMap::from([(name, default)]),
            max_upload_bytes,
        }
    }

    /// Read the configuration from the environment (see the module docs).
    pub fn from_env() -> Result<Self, String> {
        let backend = std::env::var("STORAGE_BACKEND").unwrap_or_else(|_| "local".to_string());
        let max_mb: u64 = std::env::var("MAX_UPLOAD_MB")
            .ok()
            .map(|v| {
                v.parse()
                    .map_err(|_| format!("MAX_UPLOAD_MB must be a number, got {v:?}"))
            })
            .transpose()?
            .unwrap_or(25);
        match backend.as_str() {
            "local" => {
                let data_dir = std::env::var("DATA_DIR").unwrap_or_else(|_| "data".to_string());
                let root = Path::new(&data_dir).join("files");
                Ok(Self::new(
                    Arc::new(LocalDisk::new(root)),
                    max_mb * 1024 * 1024,
                ))
            }
            other => Err(format!(
                "unknown STORAGE_BACKEND {other:?} (supported: local)"
            )),
        }
    }

    /// A throwaway local store in a fresh temp directory, for tests.
    pub fn temporary() -> Self {
        let root = std::env::temp_dir().join(format!("woodmouse-test-{}", uuid::Uuid::new_v4()));
        Self::new(Arc::new(LocalDisk::new(root)), 25 * 1024 * 1024)
    }

    /// The backend new uploads go to.
    pub fn default_store(&self) -> Arc<dyn FileStore> {
        self.stores[&self.default].clone()
    }

    /// The backend with this name, for reading or deleting a file it wrote.
    pub fn store(&self, name: &str) -> Option<Arc<dyn FileStore>> {
        self.stores.get(name).cloned()
    }
}
